import { readFileSync, writeFileSync } from 'node:fs'

const source = new URL('../public/articles.json', import.meta.url)
const target = new URL('../supabase/seed.sql', import.meta.url)
const updateTarget = new URL('../supabase/update_articles.sql', import.meta.url)
const articlesSeedTarget = new URL('../supabase/seed_articles.sql', import.meta.url)

const articles = JSON.parse(readFileSync(source, 'utf8'))
if (!Array.isArray(articles)) throw new Error('articles.json must contain an array')
const json = JSON.stringify(articles)
let delimiter = '$archive_seed$'
while (json.includes(delimiter)) delimiter = delimiter.replace('$archive_', '$archive_x')

writeFileSync(target,
  '-- Generated by npm run prepare:supabase. Existing live data is never overwritten.\n' +
  `insert into public.archive (id, articles) values (1, ${delimiter}${json}${delimiter}::jsonb)\n` +
  'on conflict (id) do nothing;\n', 'utf8')

writeFileSync(updateTarget,
  '-- Run this in Supabase SQL Editor if you want to sync existing database with articles.json\n' +
  `insert into public.archive (id, articles, revision)\n` +
  `values (1, ${delimiter}${json}${delimiter}::jsonb, 1)\n` +
  `on conflict (id) do update set articles = excluded.articles, revision = public.archive.revision + 1, updated_at = now();\n`, 'utf8')

function escapeSql(str) {
  if (str === null || str === undefined) return 'null'
  return `'${String(str).replace(/'/g, "''")}'`
}

function escapeSqlArray(arr) {
  if (!arr || !Array.isArray(arr)) return 'null'
  if (arr.length === 0) return "'{}'::text[]"
  return `array[${arr.map(escapeSql).join(', ')}]::text[]`
}

const rowsSql = articles.map((a) => {
  const id = Number(a.id)
  const slug = escapeSql(a.slug)
  const category = escapeSql(a.category)
  const categoryName = escapeSql(a.categoryName || '')
  const title = escapeSql(a.title)
  const summary = escapeSql(a.summary || '')
  const content = escapeSql(a.content || '')
  const image = escapeSql(a.image || '')
  const tags = escapeSqlArray(a.tags || [])
  const keywords = Array.isArray(a.keywords) ? escapeSqlArray(a.keywords) : 'null'
  const createdAt = escapeSql(a.createdAt || null)
  const updatedAt = escapeSql(a.updatedAt || null)
  const updated = escapeSql(a.updated || null)

  return `(${id}, ${slug}, ${category}, ${categoryName}, ${title}, ${summary}, ${content}, ${image}, ${tags}, ${keywords}, ${createdAt}, ${updatedAt}, ${updated})`
}).join(',\n')

writeFileSync(articlesSeedTarget,
  '-- Run this in Supabase SQL Editor to populate or re-sync public.articles table with all articles\n' +
  'insert into public.articles (id, slug, category, category_name, title, summary, content, image, tags, keywords, created_at, updated_at, updated)\n' +
  'values\n' +
  rowsSql + '\n' +
  'on conflict (id) do update set\n' +
  '  slug = excluded.slug,\n' +
  '  category = excluded.category,\n' +
  '  category_name = excluded.category_name,\n' +
  '  title = excluded.title,\n' +
  '  summary = excluded.summary,\n' +
  '  content = excluded.content,\n' +
  '  image = excluded.image,\n' +
  '  tags = excluded.tags,\n' +
  '  keywords = excluded.keywords,\n' +
  '  created_at = excluded.created_at,\n' +
  '  updated_at = excluded.updated_at,\n' +
  '  updated = excluded.updated,\n' +
  '  updated_time = now();\n', 'utf8')

console.log(`Prepared seed.sql, update_articles.sql, and seed_articles.sql with ${articles.length} articles.`)

