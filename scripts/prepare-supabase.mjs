import { readFileSync, writeFileSync } from 'node:fs'

const source = new URL('../public/articles.json', import.meta.url)
const target = new URL('../supabase/seed.sql', import.meta.url)
const updateTarget = new URL('../supabase/update_articles.sql', import.meta.url)
const articles = JSON.parse(readFileSync(source, 'utf8'))
if (!Array.isArray(articles)) throw new Error('articles.json must contain an array')
const json = JSON.stringify(articles)
let delimiter = '$archive_seed$'
while (json.includes(delimiter)) delimiter = delimiter.replace('$archive_', '$archive_x')
writeFileSync(target,
  '-- Generated by npm run prepare:supabase. Existing live data is never overwritten.\n' +
  `insert into public.archive (id, articles) values (1, ${delimiter}${json}${delimiter}::jsonb)\n` +
  'on conflict (id) do nothing;\n', 'utf8')
writeFileSync(updateTarget,
  '-- Run this in Supabase SQL Editor if you want to sync existing database with articles.json\n' +
  `insert into public.archive (id, articles, revision)\n` +
  `values (1, ${delimiter}${json}${delimiter}::jsonb, 1)\n` +
  `on conflict (id) do update set articles = excluded.articles, revision = public.archive.revision + 1, updated_at = now();\n`, 'utf8')
console.log(`Prepared supabase/seed.sql and supabase/update_articles.sql with ${articles.length} articles.`)
